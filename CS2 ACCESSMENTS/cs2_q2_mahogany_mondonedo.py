scores = [85, 92, 78, 90, 88]

def display_scores(score_list):
    print("\n--- Current Student Scores ---")
    for i in range(len(score_list)):
        print(f"Student #{i + 1} (Index {i}): {score_list[i]}")
    print("------------------------------")

def search_score(score_list):
    target = int(input("Enter the score you want to search for: "))
    found = False

    for i in range(len(score_list)):
        if score_list[i] == target:
            print(f"Success! Score {target} was found at Index {i} (Student #{i + 1}).")
            found = True

    if not found:
        print(f"Sorry, the score {target} is not in the list.")

def compute_average(score_list):
    total = 0
    for score in score_list:
        total = total + score

    average = total / len(score_list)
    print(f"Total Score: {total}")
    print(f"Average Score: {average:.2f}")

def update_score(score_list):
    display_scores(score_list)
    index = int(input("Enter the Index number of the score you want to change: "))

    if 0 <= index < len(score_list):
        new_score = int(input(f"Enter the new score for Index {index}: "))
        score_list[index] = new_score
        print("Score updated successfully!")
    else:
        print("Invalid index! Please choose a number shown in the list.")

def main():
    while True:
        print("=== Student Score Analyzer ===")
        print("Select the number of the operation you want to perform:")
        print("1. Display Scores")
        print("2. Search Score")
        print("3. Compute Average Score")
        print("4. Update Score")
        print("5. Display Updated Scores")
        print("6. Exit")

        choice = input("Enter your choice (1-6): ")

        if choice == "1":
            display_scores(scores)
        elif choice == "2":
            search_score(scores)
        elif choice == "3":
            compute_average(scores)
        elif choice == "4":
            update_score(scores)
        elif choice == "5":
            display_scores(scores)
        elif choice == "6":
            print("Thank you for using the Student Score Analyzer. Goodbye!")
            break
        else:
            print("Invalid choice! Please enter a number from 1 to 6.")

main()